--      other code shares.
--   3. The rating summary is STORED (rating_summary). customer-api cannot run
--      the platform's query across a service boundary. It is written in the
--      same transaction as each review change and recomputed nightly.
--
-- NO FOREIGN KEYS to other services' ids (tenant, storefront, branch, booking,
-- customer, staff). The only foreign keys are between this service's tables.
--
-- Enum type names are SUFFIXED (review_state, not review): Postgres keeps
-- tables and types in one namespace.
--
-- Every statement is retry-safe.

