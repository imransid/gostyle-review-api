-- rating_summary: the counts must describe one consistent set of reviews.
-- The histogram and the language split are breakdowns of the count, and the
-- sum is what the histogram weighs. A drifted row fails loudly here instead of
-- printing a wrong star on a public page.
DO $$ BEGIN
    ALTER TABLE "rating_summary" ADD CONSTRAINT "rating_summary_consistent"
        CHECK (
            "review_count" >= 0
            AND "star_1" >= 0 AND "star_2" >= 0 AND "star_3" >= 0
            AND "star_4" >= 0 AND "star_5" >= 0
            AND "count_en" >= 0 AND "count_ar" >= 0
            AND "star_1" + "star_2" + "star_3" + "star_4" + "star_5" = "review_count"
            AND "count_en" + "count_ar" = "review_count"
            AND "rating_sum" = "star_1" + 2 * "star_2" + 3 * "star_3" + 4 * "star_4" + 5 * "star_5"
        );
EXCEPTION WHEN duplicate_object THEN null;
END $$;
